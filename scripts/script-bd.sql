-- Gatilho de auditoria das doações
CREATE OR ALTER TRIGGER TRG_ELO_AUDITORIA_DOACAO
ON TB_ELO_DOACAO
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO TB_ELO_AUDITORIA_DOACAO (ID_DOACAO, OPERACAO, STATUS_ANTIGO, STATUS_NOVO, LOCAL_ANTIGO, LOCAL_NOVO)
    SELECT COALESCE(i.ID_DOACAO, d.ID_DOACAO),
           CASE
               WHEN d.ID_DOACAO IS NULL THEN 'INSERT'
               WHEN i.ID_DOACAO IS NULL THEN 'DELETE'
               ELSE 'UPDATE'
           END,
           d.STATUS, i.STATUS, d.LOCAL_RETIRADA, i.LOCAL_RETIRADA
      FROM inserted i
      FULL OUTER JOIN deleted d ON d.ID_DOACAO = i.ID_DOACAO;
END;
GO

-- Gatilho de controle das reservas
CREATE OR ALTER TRIGGER TRG_ELO_RESERVA_STATUS
ON TB_ELO_RESERVA
AFTER INSERT, UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @mensagem NVARCHAR(200);

    IF NOT EXISTS (SELECT 1 FROM deleted)
    BEGIN
        SELECT TOP 1 @mensagem = CONCAT(N'A doação ', i.ID_DOACAO, N' não está disponível para reserva.')
          FROM inserted i
          JOIN TB_ELO_DOACAO d WITH (UPDLOCK) ON d.ID_DOACAO = i.ID_DOACAO
         WHERE d.STATUS <> 'DISPONIVEL';
        IF @mensagem IS NOT NULL THROW 50011, @mensagem, 1;

        SELECT TOP 1 @mensagem = CONCAT(N'A doação ', i.ID_DOACAO, N' não possui alimentos cadastrados.')
          FROM inserted i
         WHERE NOT EXISTS (SELECT 1 FROM TB_ELO_ITEM_DOACAO it WHERE it.ID_DOACAO = i.ID_DOACAO);
        IF @mensagem IS NOT NULL THROW 50012, @mensagem, 1;

        SELECT TOP 1 @mensagem = CONCAT(N'A doação ', i.ID_DOACAO, N' possui alimento com a validade vencida.')
          FROM inserted i
          JOIN TB_ELO_ITEM_DOACAO it ON it.ID_DOACAO = i.ID_DOACAO
         WHERE it.DT_VALIDADE < CAST(i.DT_RESERVA AS DATE);
        IF @mensagem IS NOT NULL THROW 50013, @mensagem, 1;

        UPDATE d
           SET STATUS = 'RESERVADA'
          FROM TB_ELO_DOACAO d
          JOIN inserted i ON i.ID_DOACAO = d.ID_DOACAO;
        RETURN;
    END;

    IF NOT UPDATE(STATUS) RETURN;

    SELECT TOP 1 @mensagem = CONCAT(N'A reserva ', d.ID_RESERVA, N' já foi finalizada.')
      FROM inserted i
      JOIN deleted d ON d.ID_RESERVA = i.ID_RESERVA
     WHERE d.STATUS <> i.STATUS
       AND d.STATUS <> 'PENDENTE';
    IF @mensagem IS NOT NULL THROW 50014, @mensagem, 1;

    UPDATE r
       SET DT_RETIRADA = SYSDATETIME()
      FROM TB_ELO_RESERVA r
      JOIN inserted i ON i.ID_RESERVA = r.ID_RESERVA
      JOIN deleted d ON d.ID_RESERVA = i.ID_RESERVA
     WHERE i.STATUS = 'CONCLUIDA' AND d.STATUS = 'PENDENTE' AND r.DT_RETIRADA IS NULL;

    UPDATE dc
       SET STATUS = CASE i.STATUS WHEN 'CONCLUIDA' THEN 'CONCLUIDA' ELSE 'DISPONIVEL' END
      FROM TB_ELO_DOACAO dc
      JOIN inserted i ON i.ID_DOACAO = dc.ID_DOACAO
      JOIN deleted d ON d.ID_RESERVA = i.ID_RESERVA
     WHERE d.STATUS = 'PENDENTE'
       AND i.STATUS IN ('CONCLUIDA', 'CANCELADA');
END;
GO

