    CONSTRAINT PK_ELO_DOACAO PRIMARY KEY (ID_DOACAO),
    CONSTRAINT CK_ELO_DOACAO_STATUS CHECK (STATUS IN ('DISPONIVEL', 'RESERVADA', 'CONCLUIDA', 'CANCELADA', 'VENCIDA')),
    CONSTRAINT FK_ELO_DOACAO_DOADOR FOREIGN KEY (ID_DOADOR) REFERENCES TB_ELO_USUARIO (ID_USUARIO)
