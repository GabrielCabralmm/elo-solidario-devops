CREATE TABLE TB_ELO_DOACAO (
    ID_DOACAO      BIGINT IDENTITY(1, 1) NOT NULL,
    ID_DOADOR      BIGINT        NOT NULL,
    TITULO         NVARCHAR(100) NOT NULL,
    BAIRRO         NVARCHAR(60)  NOT NULL,
    LOCAL_RETIRADA NVARCHAR(150) NOT NULL,
    OBSERVACAO     NVARCHAR(300) NULL,
