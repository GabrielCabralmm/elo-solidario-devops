    ID_CATEGORIA  BIGINT        NOT NULL,
    NOME          NVARCHAR(80)  NOT NULL,
    CONSERVACAO   NVARCHAR(12)  NOT NULL,
    CALORIAS_100G DECIMAL(6, 1) NOT NULL,
